// scripts/gen-slot-configs.mjs
//
// Generates supabase/functions/_shared/slot-configs.ts from the REAL paytables
// in src/lib/slots/games*.ts.
//
// WHY GENERATE
//
// The edge bundle cannot import src/lib/slots/games.ts: that file declares
// `buildGrid`/`resolve`/`r2` alongside the engine it imports, and splicing both
// into one file is a duplicate declaration that throws on load. It also carries
// 44 `art` paths the server never uses.
//
// The alternative — a hand-copied paytable — is exactly the drift that once made
// a wheel pay a multiplier the board never showed. So the numbers are read from
// the source of truth here, and `npm run test:slotvalue` re-reads them from BOTH
// sides on every run to prove they still match.
import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const ROOT = new URL('..', import.meta.url).pathname
const OUT = `${ROOT}supabase/functions/_shared/slot-configs.ts`

/** Load a config module with its artwork import removed. */
async function load(path, names) {
  const src = readFileSync(path, 'utf8')
    .split('\n')
    .filter((l) => !l.startsWith('import '))
    .join('\n')
    .replace(/^export /gm, '')
    // The artwork base is the only thing these modules need from the browser.
    .replace(/\$\{ASSET_BASE\}/g, '/')
  const js = ts.transpileModule(`${src}\nexport { ${names.join(', ')} };\n`, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  }).outputText
  const file = `/tmp/slotgen-${Math.random().toString(36).slice(2)}.mjs`
  writeFileSync(file, js)
  return import(file)
}

const a = await load(`${ROOT}src/lib/slots/games.ts`, ['CHAPE', 'BLUE_MOUNTAIN'])
const b = await load(`${ROOT}src/lib/slots/games2.ts`, ['BAZAAR', 'BODA'])
const { CRATERS } = await load(`${ROOT}src/lib/slots/craters.ts`, ['CRATERS'])

const configs = { CHAPE: a.CHAPE, BLUE_MOUNTAIN: a.BLUE_MOUNTAIN, BAZAAR: b.BAZAAR, BODA: b.BODA }

/** Only the fields resolution reads. Art, glyph, colour and name are dropped. */
const strip = (c) => ({
  id: c.id,
  name: c.name,
  reels: c.reels,
  rows: c.rows,
  symbols: c.symbols.map((s) => ({ id: s.id, weight: s.weight, tier: s.tier, pay: s.pay })),
  wild: c.wild,
  scatter: c.scatter,
  scatterTrigger: c.scatterTrigger,
  freeSpins: c.freeSpins,
  scatterPay: c.scatterPay,
  omen: c.omen,
  badLuck: c.badLuck,
  maxWin: c.maxWin,
})

const body = Object.entries(configs)
  .map(([k, c]) => `export const ${k} = ${JSON.stringify(strip(c), null, 2)} as unknown as SlotConfig`)
  .join('\n\n')

const out = `// GENERATED by scripts/gen-slot-configs.mjs — do not edit by hand.
//
// The paytables the server settles with, stripped to the fields resolution reads.
// Generated from src/lib/slots/games.ts and games2.ts, which are the source of
// truth the board renders from. \`npm run test:slotvalue\` re-derives both sides
// and fails if any pay, weight, trigger or cap differs.

/*
 * Declared here rather than imported from src/lib/slots/engine.ts: the edge
 * bundle splices that module inside a closure, and a type cannot cross a closure
 * boundary. This is the structural shape resolution actually reads.
 */
export type SlotConfig = {
  id: string
  reels: number
  rows: number
  symbols: { id: string; weight: number; tier: string; pay?: number[] }[]
  wild: string
  scatter: string
  scatterTrigger: number
  freeSpins: number
  scatterPay: [number, number, number]
  omen?: { symbol: string; trigger: number; fine: number }
  badLuck?: string[]
  maxWin: number
}

// The full config, not just its dimensions: Craters resolves its own crate and
// boda features against the symbol table, and a config without symbols throws
// on the first weighted pick.
export const CRATERS_CONFIG = ${JSON.stringify(strip(CRATERS), null, 2)} as unknown as SlotConfig

${body}
`
writeFileSync(OUT, out)
console.log(`wrote ${OUT} (${out.length} bytes)`)
for (const [k, c] of Object.entries(configs)) {
  console.log(`  ${k.padEnd(14)} ${c.reels}x${c.rows} wild=${c.wild} scatter=${c.scatter} max=${c.maxWin}`)
}
console.log(`  CRATERS        ${CRATERS.reels}x${CRATERS.rows} max=${CRATERS.maxWin}`)
